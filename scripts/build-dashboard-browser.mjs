/**
 * Concatenate the dashboard modules into one classic script.
 * htmlpreview only evaluates classic scripts (it skips type="module"),
 * and raw.githubusercontent.com serves .js as text/plain, which browsers
 * refuse to run as a module. One classic file is fetched and eval'd.
 *
 *   npm run build:dashboard
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export function renderBrowserBundle(chainSrc, appSrc) {
  if (!chainSrc.includes("export const CHAIN_ID")) {
    throw new Error("dashboard/chain.js no longer exports CHAIN_ID");
  }
  if (!appSrc.includes('from "./chain.js"')) {
    throw new Error('dashboard/app.js no longer imports "./chain.js"');
  }
  const chain = chainSrc.replace(/^export /gm, "");
  if (/^export /m.test(chain)) throw new Error("an export survived in the chain bundle");
  const app = appSrc.replace(/^import \{[\s\S]*?\} from "\.\/chain\.js";\r?\n/, "");
  if (/^\s*import\s/m.test(app)) throw new Error("an import survived in the app bundle");
  return `/* Generated by scripts/build-dashboard-browser.mjs — do not edit.
   Classic script so htmlpreview (and GitHub Pages) can run the inspector.
   Rebuild: npm run build:dashboard
*/
"use strict";
${chain}
${app}`;
}

const entry = process.argv[1];
if (entry && import.meta.url === pathToFileURL(entry).href) {
  const chainSrc = readFileSync(join(root, "dashboard/chain.js"), "utf8");
  const appSrc = readFileSync(join(root, "dashboard/app.js"), "utf8");
  const next = renderBrowserBundle(chainSrc, appSrc);
  const dest = join(root, "dashboard/browser.js");
  if (process.argv.includes("--check")) {
    const current = readFileSync(dest, "utf8");
    if (current !== next) {
      console.error("dashboard/browser.js is stale. Run npm run build:dashboard");
      process.exit(1);
    }
    console.log("dashboard/browser.js matches chain.js and app.js");
  } else {
    writeFileSync(dest, next);
    console.log("wrote dashboard/browser.js");
  }
}
